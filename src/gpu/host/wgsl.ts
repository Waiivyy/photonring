// Generated WGSL: uniform structs and constants taken from the TypeScript sources of truth
// (physics library, star layers, colour table), so CPU and GPU cannot disagree on them.
import { STAR_LAYERS } from '../../physics/index.ts';
import { wgslStruct, type StructField } from './layout.ts';

/** Per-dispatch parameters of the compute shaders. */
export const FRAME_FIELDS: readonly StructField[] = [
  ['position', 'vec3f'],
  ['r0', 'f32'],
  ['forward', 'vec3f'],
  ['tanHalfFovY', 'f32'],
  ['right', 'vec3f'],
  ['aspect', 'f32'],
  ['up', 'vec3f'],
  ['M', 'f32'],
  ['dphi', 'f32'],
  ['cosStep', 'f32'],
  ['sinStep', 'f32'],
  ['gObserver', 'f32'],
  ['width', 'u32'],
  ['height', 'u32'],
  ['maxSteps', 'u32'],
  ['mode', 'u32'],
  ['tileOrigin', 'vec2u'],
  ['tileSize', 'vec2u'],
  ['sky', 'u32'],
];

/** Parameters of the tone-mapping blit. */
export const BLIT_FIELDS: readonly StructField[] = [
  ['exposure', 'f32'],
  ['toneMapping', 'u32'],
];

/**
 * Radial-ray threshold on |sin psi| for the f32 shader. The f64 library uses 1e-7; in f32 the
 * tangential part of an exactly radial direction has rounding noise near 1e-7, so the shader
 * uses 1e-6. Rays between the two thresholds are within 1e-6 rad of radial and end the same way.
 */
export const GPU_RADIAL_SIN = 1e-6;

export interface LutParams {
  readonly size: number;
  readonly tMin: number;
  readonly tMax: number;
}

const f32 = (v: number) => {
  const s = String(v);
  return /[.e]/.test(s) ? s : `${s}.0`;
};

export function wgslHeader(lut: LutParams): string {
  const layers = STAR_LAYERS.map(
    (l) => `vec4f(${f32(l.cellsPerUnit)}, ${f32(l.probability)}, ${f32(l.brightness)}, 0.0)`,
  );
  const salts = STAR_LAYERS.map((l) => `${l.salt >>> 0}u`);
  return [
    '// Generated by src/gpu/host/wgsl.ts. Do not edit by hand.',
    'const ESCAPED: u32 = 0u;',
    'const CAPTURED: u32 = 1u;',
    'const STEP_LIMIT: u32 = 2u;',
    `const RADIAL_SIN: f32 = ${f32(GPU_RADIAL_SIN)};`,
    `const STAR_LAYER_COUNT: u32 = ${STAR_LAYERS.length}u;`,
    `var<private> STAR_LAYERS: array<vec4f, ${STAR_LAYERS.length}> = array<vec4f, ${STAR_LAYERS.length}>(${layers.join(', ')});`,
    `var<private> STAR_SALTS: array<u32, ${STAR_LAYERS.length}> = array<u32, ${STAR_LAYERS.length}>(${salts.join(', ')});`,
    `const STAR_TAIL: f32 = ${f32(Math.exp(-8))};`,
    `const LUT_SIZE: u32 = ${lut.size}u;`,
    `const LUT_TMIN: f32 = ${f32(lut.tMin)};`,
    `const LUT_TMAX: f32 = ${f32(lut.tMax)};`,
    `const LUT_INV_LOG_RANGE: f32 = ${f32((lut.size - 1) / Math.log(lut.tMax / lut.tMin))};`,
    wgslStruct('Params', FRAME_FIELDS),
    wgslStruct('BlitParams', BLIT_FIELDS),
  ].join('\n');
}
